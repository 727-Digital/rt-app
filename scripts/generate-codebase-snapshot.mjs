#!/usr/bin/env node
/**
 * Walks the project's source tree and writes a single concatenated
 * text snapshot to supabase/functions/_shared/codebase-snapshot.txt.
 * The chat-help edge function loads this snapshot at startup and feeds
 * it to Claude as cached system context — so the help bot always
 * answers based on the exact code in the current deploy.
 *
 * Re-runs on every `npm run build` (Vercel) and on every
 * `npm run snapshot` (manual). Keep the included paths narrow enough
 * that the snapshot stays under ~190K tokens so it fits inside
 * Claude's 200K context window with room for the user's question and
 * a streaming reply.
 */

import { readdirSync, statSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';

const ROOT = process.cwd();
// Output as a TS module so Supabase's deploy bundler picks it up via
// the function's import graph. A plain .txt file wouldn't be uploaded
// — Supabase only deploys files reachable through imports.
const OUT_PATH = join(
  ROOT,
  'supabase',
  'functions',
  '_shared',
  'codebase-snapshot.ts',
);

// Source roots the bot actually needs to understand the app.
// Intentionally excluding supabase/migrations (noisy SQL baselines that
// don't help answer rep questions) and node_modules / dist.
const INCLUDE_ROOTS = [
  { path: 'src', extensions: ['.ts', '.tsx'] },
  { path: 'supabase/functions', extensions: ['.ts'] },
];

const EXCLUDE_DIRS = new Set(['node_modules', 'dist', 'build', '.git']);

// Skip the snapshot's own output file. Without this, every regeneration
// would embed the previous base64 blob inside the new snapshot —
// doubling the size each run.
const EXCLUDE_FILES = new Set(['codebase-snapshot.ts']);

function walk(dir, extensions, hits) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (EXCLUDE_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    let s;
    try {
      s = statSync(full);
    } catch {
      continue;
    }
    if (s.isDirectory()) {
      walk(full, extensions, hits);
    } else if (s.isFile()) {
      if (EXCLUDE_FILES.has(entry)) continue;
      if (extensions.some((ext) => entry.endsWith(ext))) {
        hits.push(full);
      }
    }
  }
}

const files = [];
for (const root of INCLUDE_ROOTS) {
  walk(join(ROOT, root.path), root.extensions, files);
}
files.sort();

const parts = [];
parts.push(
  `# Reliable Turf codebase snapshot (auto-generated)\n` +
    `Generated: ${new Date().toISOString()}\n` +
    `Files: ${files.length}\n` +
    `This file is read by supabase/functions/chat-help at startup ` +
    `and supplied to Claude as cached system context.\n`,
);

let totalBytes = 0;
for (const file of files) {
  const rel = relative(ROOT, file);
  let body;
  try {
    body = readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  parts.push(`\n\n----- FILE: ${rel} -----\n${body}`);
  totalBytes += body.length;
}

mkdirSync(dirname(OUT_PATH), { recursive: true });

// Base64-encode the snapshot before embedding. Supabase's deploy
// bundler scans source for `import` / `from "..."` patterns and tries
// to resolve them — and the snapshot embeds the literal text of every
// project file, including all their imports. Without encoding, the
// bundler chokes on phantom import paths inside string literals and
// fails to ship the function. Encoding hides those patterns; we
// decode once at function startup.
const base64Snapshot = Buffer.from(parts.join(''), 'utf8').toString('base64');
const tsModule =
  `// AUTO-GENERATED by scripts/generate-codebase-snapshot.mjs\n` +
  `// Do not edit by hand. Re-run \`npm run snapshot\` to regenerate.\n` +
  `// Snapshot is base64-encoded to keep Supabase's bundler from\n` +
  `// scanning embedded source for spurious import resolutions.\n\n` +
  `export const CODEBASE_SNAPSHOT_B64: string = ${JSON.stringify(base64Snapshot)};\n`;
writeFileSync(OUT_PATH, tsModule, 'utf8');

// totalBytes is the decoded snapshot size — what Claude actually
// receives at query time (we atob the base64 inside the function).
// The on-disk file is larger due to base64 expansion, but that's not
// what matters for the context window.
const kb = (totalBytes / 1024).toFixed(0);
const approxTokens = Math.round(totalBytes / 4);
console.log(
  `[codebase-snapshot] ${files.length} files, ${kb}KB decoded (~${approxTokens.toLocaleString()} tokens) → ${relative(ROOT, OUT_PATH)}`,
);

if (approxTokens > 190_000) {
  console.warn(
    `[codebase-snapshot] WARNING: decoded snapshot is ${approxTokens} tokens; ` +
      `Claude 4.5 Sonnet context is 200K. Consider narrowing INCLUDE_ROOTS.`,
  );
}
